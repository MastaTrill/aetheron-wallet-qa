import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const read = file => readFileSync(new URL(file,import.meta.url),'utf8');
const html=read('./site/index.html'), js=read('./site/app.js'),css=read('./site/style.css');
assert.match(html, /noindex,nofollow/);
assert.match(html, /Content-Security-Policy/);
assert.match(html, /choose Cancel in MetaMask/);
assert.match(html, /wallet-qa\.aetrs\.com/);
assert.match(js, /const expectedOrigin = 'https:\/\/wallet-qa\.aetrs\.com'/);
assert.match(js, /'eth_accounts'/);
assert.match(js, /'eth_requestAccounts'/);
assert.match(js, /'wallet_revokePermissions'/);
assert.match(html, /Disconnect this QA site's account access only/);
assert.match(js, /Number\(error\.code\) === 4001/);
assert.match(js, /list\.length !== 0/);
const methods=[...js.matchAll(/method:\s*'([^']+)'/g)].map(x=>x[1]);
assert.deepEqual([...new Set(methods)].sort(),['eth_accounts','eth_requestAccounts','wallet_revokePermissions']);
assert.doesNotMatch(js,/\b(fetch|XMLHttpRequest|sendBeacon|localStorage|sessionStorage)\b/);
assert.doesNotMatch(html,/http:\/\/|https:\/\/(?!wallet-qa\.aetrs\.com)/);
assert.ok(css.length>200);
assert.equal(read('./site/robots.txt'),'User-agent: *\nDisallow: /\n');
console.log('PASS: isolated account-rejection QA has no signing, transaction, network or storage APIs');
